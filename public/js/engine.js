(function () {
  "use strict";

  const storage = window.CaYaStorage;
  const monthNames = ["Ocak", "Şubat", "Mart", "Nisan", "Mayıs", "Haziran", "Temmuz", "Ağustos", "Eylül", "Ekim", "Kasım", "Aralık"];
  const monthlyMembershipTypes = new Set(["Aylık üyelik", "3 aylık üyelik", "6 aylık üyelik", "Yıllık üyelik"]);

  function todayDate() {
    const d = new Date();
    d.setHours(12, 0, 0, 0);
    return d;
  }

  function parseISODate(iso) {
    if (!iso) return null;
    const d = new Date(`${iso}T12:00:00`);
    return Number.isNaN(d.getTime()) ? null : d;
  }

  function isoFromYMD(year, month, day) {
    const safeDay = Math.min(day, new Date(year, month + 1, 0).getDate());
    return `${year}-${String(month + 1).padStart(2, "0")}-${String(safeDay).padStart(2, "0")}`;
  }

  function periodKey(year, month) {
    return `${year}-${String(month + 1).padStart(2, "0")}`;
  }

  function periodLabel(year, month) {
    return `${monthNames[month]} ${year}`;
  }

  function isCustomFee(value) {
    return value !== null && value !== undefined && value !== "" && !Number.isNaN(Number(value));
  }

  function effectiveBranchMonthlyFee(branch, isoDate, enrollment) {
    const fallback = Number(branch?.monthlyFee || 0);
    const history = Array.isArray(branch?.feeHistory) ? branch.feeHistory.slice() : [];
    if (!history.length || !isoDate) return fallback;

    const sorted = history
      .filter((item) => item.effectiveDate && isCustomFee(item.amount))
      .sort((a, b) => String(a.effectiveDate).localeCompare(String(b.effectiveDate)));

    let chosen = fallback;
    const enrollmentCreated = String(enrollment?.createdAt || "");
    sorted.forEach((entry) => {
      const effectiveDate = String(entry.effectiveDate || "");
      const changedDate = String(entry.changedDate || "");
      const appliesByPeriod = effectiveDate && effectiveDate <= String(isoDate);
      const appliesToNewEnrollment =
        changedDate &&
        enrollmentCreated &&
        enrollmentCreated >= changedDate &&
        String(isoDate) >= changedDate;

      if (appliesByPeriod || appliesToNewEnrollment) {
        chosen = Number(entry.amount || 0);
      }
    });
    return chosen;
  }

  function enrollmentAmount(enrollment, branch, dueISO) {
    if (isCustomFee(enrollment.customFee)) {
      return { amount: Number(enrollment.customFee), feeSource: "custom" };
    }
    return { amount: effectiveBranchMonthlyFee(branch, dueISO, enrollment), feeSource: "branch" };
  }

  function isFuturePaymentPeriod(payment) {
    const period = String(payment?.period || "");
    if (!period) return false;
    const today = todayDate();
    const currentPeriod = periodKey(today.getFullYear(), today.getMonth());
    return period > currentPeriod;
  }

  function generateExpectedPaymentsForEnrollment(enrollment, branches) {
    if (!enrollment || !enrollment.startDate) return [];
    if (enrollment.status === "Pasif" || enrollment.status === "Ayrıldı") return [];
    if (!monthlyMembershipTypes.has(enrollment.membershipType || "Aylık üyelik")) return [];

    const branch = branches.find((b) => b.id === enrollment.branchId);
    const start = parseISODate(enrollment.startDate);
    if (!start) return [];

    const today = todayDate();
    const endDate = enrollment.endDate ? parseISODate(enrollment.endDate) : null;
    const stop = endDate && endDate < today ? endDate : today;
    if (start > stop) return [];

    const startDay = start.getDate();
    const cursor = new Date(start.getFullYear(), start.getMonth(), 1, 12, 0, 0);
    const stopMonth = new Date(stop.getFullYear(), stop.getMonth(), 1, 12, 0, 0);
    const payments = [];

    let safety = 0;
    while (cursor <= stopMonth && safety++ < 240) {
      const year = cursor.getFullYear();
      const month = cursor.getMonth();
      const dueISO = isoFromYMD(year, month, startDay);
      const { amount, feeSource } = enrollmentAmount(enrollment, branch, dueISO);
      if (amount <= 0) {
        cursor.setMonth(cursor.getMonth() + 1);
        continue;
      }
      payments.push({
        studentId: enrollment.studentId,
        branchId: enrollment.branchId,
        enrollmentId: enrollment.id,
        period: periodKey(year, month),
        totalAmount: amount,
        paidAmount: 0,
        dueDate: dueISO,
        status: "Bekliyor",
        description: `${periodLabel(year, month)} aylık ücret`,
        feeSource,
        autoGenerated: true,
        transactions: []
      });
      cursor.setMonth(cursor.getMonth() + 1);
    }

    return payments;
  }

  function ensureStudentPayments() {
    const enrollments = storage.getData(storage.KEYS.enrollments, []);
    const existing = storage.getData(storage.KEYS.payments, []);
    const branches = storage.getData(storage.KEYS.branches, []);
    if (!enrollments.length) return { added: 0, updated: 0 };

    const index = new Map();
    existing.forEach((payment) => {
      if (payment.enrollmentId && payment.period) {
        index.set(`${payment.enrollmentId}_${payment.period}`, payment);
      }
    });

    const next = existing.slice();
    let added = 0;
    let updated = 0;

    enrollments.forEach((enrollment) => {
      const expected = generateExpectedPaymentsForEnrollment(enrollment, branches);
      const branch = branches.find((b) => b.id === enrollment.branchId);

      expected.forEach((candidate) => {
        const key = `${candidate.enrollmentId}_${candidate.period}`;
        const existingPayment = index.get(key);

        if (!existingPayment) {
          const newPayment = { ...candidate, id: storage.generateId("pay") };
          next.push(newPayment);
          index.set(key, newPayment);
          added++;
          return;
        }

        if (!existingPayment.autoGenerated) return;
        if (existingPayment.status === "İptal") return;
        const paidAmount = Number(existingPayment.paidAmount || 0);
        if (paidAmount > 0) return;

        const canUpdateFuture = isFuturePaymentPeriod(existingPayment);
        const canCorrectHistoricalBranchFee =
          !canUpdateFuture &&
          candidate.feeSource === "branch" &&
          existingPayment.feeSource === "branch" &&
          Array.isArray(branch?.feeHistory) &&
          branch.feeHistory.length > 0;

        if (!canUpdateFuture && !canCorrectHistoricalBranchFee) return;

        if (
          candidate.feeSource === "branch" &&
          existingPayment.feeSource === "branch" &&
          Number(existingPayment.totalAmount) !== candidate.totalAmount
        ) {
          existingPayment.totalAmount = candidate.totalAmount;
          existingPayment.description = candidate.description;
          updated++;
        }

        if (!canUpdateFuture) return;

        if (candidate.feeSource === "custom" && existingPayment.feeSource === "branch") {
          existingPayment.totalAmount = candidate.totalAmount;
          existingPayment.feeSource = "custom";
          updated++;
        }
        if (candidate.feeSource === "branch" && existingPayment.feeSource === "custom") {
          existingPayment.totalAmount = candidate.totalAmount;
          existingPayment.feeSource = "branch";
          updated++;
        }
      });
    });

    const normalized = next.map((payment) => storage.normalizePayment(payment));
    if (added > 0 || updated > 0) {
      storage.setData(storage.KEYS.payments, normalized);
    }
    return { added, updated };
  }

  function generateExpectedSalariesForTeacher(teacher) {
    if (!teacher) return [];
    if (teacher.status === "Pasif") return [];
    const amount = Number(teacher.monthlySalary || 0);
    if (amount <= 0) return [];

    const rawStart = teacher.startDate || teacher.salaryEffectiveDate || storage.todayISO();
    const start = parseISODate(rawStart);
    if (!start) return [];
    const today = todayDate();
    if (start > today) return [];

    const startDay = start.getDate();
    const cursor = new Date(start.getFullYear(), start.getMonth(), 1, 12, 0, 0);
    const stopMonth = new Date(today.getFullYear(), today.getMonth(), 1, 12, 0, 0);
    const items = [];
    let safety = 0;

    while (cursor <= stopMonth && safety++ < 240) {
      const year = cursor.getFullYear();
      const month = cursor.getMonth();
      const dueISO = isoFromYMD(year, month, startDay);
      const effective = effectiveSalaryFor(teacher, dueISO);
      items.push({
        teacherId: teacher.id,
        period: periodKey(year, month),
        totalAmount: effective,
        paidAmount: 0,
        dueDate: dueISO,
        status: "Bekliyor",
        description: `${periodLabel(year, month)} aylık maaş`,
        autoGenerated: true,
        transactions: []
      });
      cursor.setMonth(cursor.getMonth() + 1);
    }
    return items;
  }

  function effectiveSalaryFor(teacher, isoDate) {
    const history = Array.isArray(teacher.salaryHistory) ? teacher.salaryHistory.slice() : [];
    if (!history.length) return Number(teacher.monthlySalary || 0);

    const sorted = history
      .filter((item) => item.effectiveDate)
      .sort((a, b) => String(a.effectiveDate).localeCompare(String(b.effectiveDate)));

    let chosen = Number(teacher.monthlySalary || 0);
    sorted.forEach((entry) => {
      if (String(entry.effectiveDate) <= String(isoDate)) {
        chosen = Number(entry.amount || 0);
      }
    });
    return chosen;
  }

  function normalizeSalary(salary) {
    const totalAmount = Number(salary.totalAmount || 0);
    const paidAmount = Math.min(Number(salary.paidAmount || 0), totalAmount);
    const remainingAmount = Math.max(totalAmount - paidAmount, 0);
    const isPastDue = salary.dueDate && salary.dueDate < storage.todayISO();
    let status = salary.status || "Bekliyor";

    if (status !== "İptal") {
      if (remainingAmount <= 0) {
        status = "Ödendi";
      } else if (isPastDue) {
        status = "Gecikti";
      } else if (paidAmount > 0) {
        status = "Kısmi ödendi";
      } else {
        status = "Bekliyor";
      }
    }

    return { ...salary, totalAmount, paidAmount, remainingAmount, status };
  }

  function ensureTeacherSalaries() {
    const teachers = storage.getData(storage.KEYS.teachers, []);
    const existing = storage.getData(storage.KEYS.teacherSalaries, []);
    if (!teachers.length) return { added: 0, updated: 0 };

    const index = new Map();
    existing.forEach((salary) => {
      if (salary.teacherId && salary.period) {
        index.set(`${salary.teacherId}_${salary.period}`, salary);
      }
    });

    const next = existing.slice();
    let added = 0;
    let updated = 0;

    teachers.forEach((teacher) => {
      const expected = generateExpectedSalariesForTeacher(teacher);
      expected.forEach((candidate) => {
        const key = `${candidate.teacherId}_${candidate.period}`;
        const existingSalary = index.get(key);

        if (!existingSalary) {
          const created = { ...candidate, id: storage.generateId("sal") };
          next.push(created);
          index.set(key, created);
          added++;
          return;
        }

        if (!existingSalary.autoGenerated) return;
        if (existingSalary.status === "İptal") return;
        const paidAmount = Number(existingSalary.paidAmount || 0);
        if (paidAmount > 0) return;

        if (Number(existingSalary.totalAmount) !== candidate.totalAmount) {
          existingSalary.totalAmount = candidate.totalAmount;
          existingSalary.description = candidate.description;
          updated++;
        }
      });
    });

    const normalized = next.map((salary) => normalizeSalary(salary));
    if (added > 0 || updated > 0) {
      storage.setData(storage.KEYS.teacherSalaries, normalized);
    }
    return { added, updated };
  }

  function nextPaymentForStudent(studentId, payments) {
    const today = storage.todayISO();
    return storage
      .normalizePayments(payments || storage.getData(storage.KEYS.payments, []))
      .filter((payment) => payment.studentId === studentId && payment.status !== "İptal" && Number(payment.remainingAmount || 0) > 0)
      .sort((a, b) => String(a.dueDate || "").localeCompare(String(b.dueDate || "")))[0] || null;
  }

  function daysFromToday(isoDate) {
    if (!isoDate) return null;
    const target = parseISODate(isoDate);
    if (!target) return null;
    const today = todayDate();
    return Math.round((target - today) / (24 * 60 * 60 * 1000));
  }

  function normalizeSalaries(list) {
    return (list || []).map(normalizeSalary);
  }

  function cleanupOrphanPayments() {
    const enrollments = storage.getData(storage.KEYS.enrollments, []);
    const enrollmentIds = new Set(enrollments.map((e) => e.id));
    const payments = storage.getData(storage.KEYS.payments, []);
    let removed = 0;
    const next = payments.filter((payment) => {
      if (!payment.autoGenerated) return true;
      if (!payment.enrollmentId) return true;
      if (enrollmentIds.has(payment.enrollmentId)) return true;
      if (Number(payment.paidAmount || 0) > 0) return true;
      removed++;
      return false;
    });
    if (removed > 0) storage.setData(storage.KEYS.payments, next);
    return removed;
  }

  function cleanupOrphanSalaries() {
    const teacherIds = new Set(storage.getData(storage.KEYS.teachers, []).map((t) => t.id));
    const salaries = storage.getData(storage.KEYS.teacherSalaries, []);
    let removed = 0;
    const next = salaries.filter((salary) => {
      if (!salary.autoGenerated) return true;
      if (teacherIds.has(salary.teacherId)) return true;
      if (Number(salary.paidAmount || 0) > 0) return true;
      removed++;
      return false;
    });
    if (removed > 0) storage.setData(storage.KEYS.teacherSalaries, next);
    return removed;
  }

  function runAll() {
    // Payment/salary plan generation writes owner-owned financial data. Only the
    // workspace owner runs it; scoped users would hit permission/merge issues.
    const access = window.CaYaApp && window.CaYaApp.access;
    if (access && !access.isOwner()) return null;
    try {
      cleanupOrphanPayments();
      cleanupOrphanSalaries();
      const p = ensureStudentPayments();
      const s = ensureTeacherSalaries();
      return { payments: p, salaries: s };
    } catch (error) {
      console.error("CaYaEngine error:", error);
      return null;
    }
  }

  window.CaYaEngine = {
    runAll,
    ensureStudentPayments,
    ensureTeacherSalaries,
    cleanupOrphanPayments,
    cleanupOrphanSalaries,
    nextPaymentForStudent,
    daysFromToday,
    normalizeSalary,
    normalizeSalaries,
    effectiveBranchMonthlyFee,
    effectiveSalaryFor,
    periodLabel,
    monthNames,
    isCustomFee
  };
})();
